"""Download the ground elevation under every green and save it for the page's
green view (slope arrows, height shading, putt reads).

Input : course-data.js (green outlines, from scripts/build_course.py)
        USGS 3DEP lidar elevation, 1 m resolution, public domain
        https://elevation.nationalmap.gov/arcgis/rest/services/3DEPElevation/ImageServer
Output: green-data.js  (`window.GREENS = {...}`, keyed by hole number)

Each green gets a small grid of heights covering the green plus a few metres
around it. Lidar is a bare-earth survey from a few years ago, so it shows the
real shape of the green well but can miss very small, recent changes.

Needs numpy, shapely and Pillow. Run: python scripts/build_greens.py
"""
import io
import json
import math
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

import numpy as np
from PIL import Image
from shapely.geometry import shape

ROOT = Path(__file__).resolve().parent.parent
SERVICE = "https://elevation.nationalmap.gov/arcgis/rest/services/3DEPElevation/ImageServer/exportImage"
STEP_M = 1.0      # grid spacing; the lidar itself is ~1 m
MARGIN_M = 4.0    # keep a little of the fringe around each green
LAT0 = 40.617
M_PER_DEG_LAT = 111_132.0
M_PER_DEG_LON = 111_320.0 * math.cos(math.radians(LAT0))


def load_course():
    src = (ROOT / "course-data.js").read_text(encoding="utf-8")
    return json.loads(src[src.index("{"):src.rindex("}") + 1])


def fetch_grid(w, s, e, n, nx, ny):
    q = urllib.parse.urlencode({
        "bbox": f"{w},{s},{e},{n}", "bboxSR": 4326, "imageSR": 4326,
        "size": f"{nx},{ny}", "format": "tiff", "pixelType": "F32",
        "interpolation": "RSP_BilinearInterpolation", "f": "image",
    })
    for attempt in range(5):        # the USGS service throws the odd 502
        try:
            with urllib.request.urlopen(SERVICE + "?" + q, timeout=90) as r:
                a = np.array(Image.open(io.BytesIO(r.read())), dtype=float)
            break
        except (urllib.error.URLError, OSError) as err:
            if attempt == 4:
                raise
            print(f"  retrying ({err})")
            time.sleep(3 * (attempt + 1))
    if a.shape != (ny, nx) or not np.isfinite(a).all() or a.min() < -100:
        raise RuntimeError(f"bad elevation grid {a.shape}, min {a.min()}")
    return a


def smooth(a):
    """One pass of a 3x3 [1 2 1] blur: removes lidar speckle, keeps the shape."""
    p = np.pad(a, 1, mode="edge")
    k = np.array([1.0, 2.0, 1.0])
    rows = (p[:, :-2] * k[0] + p[:, 1:-1] * k[1] + p[:, 2:] * k[2]) / 4
    return (rows[:-2] * k[0] + rows[1:-1] * k[1] + rows[2:] * k[2]) / 4


def main():
    course = load_course()
    out = {}
    for f in course["features"]["features"]:
        p = f["properties"]
        if p["kind"] != "green" or not p.get("holes"):
            continue
        b = shape(f["geometry"]).bounds
        mx, my = MARGIN_M / M_PER_DEG_LON, MARGIN_M / M_PER_DEG_LAT
        w, s, e, n = b[0] - mx, b[1] - my, b[2] + mx, b[3] + my
        nx = max(4, round((e - w) * M_PER_DEG_LON / STEP_M))
        ny = max(4, round((n - s) * M_PER_DEG_LAT / STEP_M))
        z = smooth(fetch_grid(w, s, e, n, nx, ny))
        z0 = float(z.min())
        grid = {
            # Cell centres: lon = w + (i + .5) * dx, lat = n - (j + .5) * dy; rows run north to south.
            "w": round(w, 7), "n": round(n, 7),
            "dx": (e - w) / nx, "dy": (n - s) / ny, "nx": nx, "ny": ny,
            "z0": round(z0, 2),
            "z": [int(round(v)) for v in ((z - z0) * 100).ravel()],   # centimetres above z0
        }
        for h in p["holes"]:
            out[str(h)] = grid
        print(f"hole {'/'.join(map(str, p['holes'])):>5}: {nx}x{ny} cells, "
              f"{(z.max() - z0) * 100:.0f} cm high to low")
    meta = {"source": "USGS 3DEP lidar elevation (1 m), public domain", "greens": out}
    (ROOT / "green-data.js").write_text(
        "// Generated by scripts/build_greens.py from USGS 3DEP elevation. Do not edit.\n"
        "window.GREENS = " + json.dumps(meta, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"wrote green-data.js ({len(out)} holes)")


if __name__ == "__main__":
    main()
